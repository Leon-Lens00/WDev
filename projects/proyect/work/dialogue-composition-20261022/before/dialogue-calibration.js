// Measured screen fit from evidence/verified-10.png. This is an affine preview,
// not an emulation of Warcraft's unit clipping, terrain or text-tag renderer.
export const dialogueModel=Object.freeze({width:140,height:140*809/1942,textureWidth:1024,textureHeight:512,artWidth:1942,artHeight:809,alphaBounds:[63,47,1876,763]});
export const calibrationPreset=()=>({version:1,planeWidth:91.5,planeHeight:64.7,planeTop:12.8,depth:400,frustumWidth:.81,centerY:-.49,source:'verified-10 / 1920x1080; one camera position'});
export function validateCalibration(c){
 if(!c||c.version!==1)throw Error('Perfil de calibración inválido.');
 for(const [key,min,max] of [['planeWidth',30,150],['planeHeight',20,120],['planeTop',-50,80],['depth',100,2000],['frustumWidth',.2,1.5],['centerY',-2,2]])if(!Number.isFinite(c[key])||c[key]<min||c[key]>max)throw Error('Calibración fuera de rango: '+key);
 if(typeof c.source!=='string'||c.source.length>160)throw Error('Procedencia de calibración inválida.');
 return c;
}
export function dialogueProjection(d){
 const c=validateCalibration(d.calibration??calibrationPreset()),ratio=d.layout.width/84.6;
 const zoom=c.frustumWidth/.81;
 const width=c.planeWidth*ratio*zoom,height=c.planeHeight*ratio*zoom;
 const top=c.planeTop+c.planeHeight-height-(d.layout.bottom-6)-(c.centerY+.49)*31.75;
 // Affine displacement measured from two captures of the same local camera.
 // Remains provisional until the clipping defect at the other start is fixed.
 const centerY=c.centerY+((d.layout.bottom-6)+(height-c.planeHeight)/2)/31.75;
 const frustumWidth=c.frustumWidth*ratio;
 const scale=2*c.depth*Math.tan(70*Math.PI/360)*frustumWidth/dialogueModel.width;
 return {left:(100-width)/2,top,width,height,depth:c.depth,frustumWidth,centerY,scale,clipped:top<0||top+height>100||width>100};
}
export function projectionJass(d){const p=dialogueProjection(d);return `// Generated by UI Studio; affine calibration remains provisional.\nlibrary DialogueProjection\nglobals\n constant real DIALOGUE_DEPTH = ${p.depth.toFixed(5)}\n constant real DIALOGUE_FRUSTUM_WIDTH = ${p.frustumWidth.toFixed(6)}\n constant real DIALOGUE_CENTER_Y = ${p.centerY.toFixed(6)}\n constant real DIALOGUE_MODEL_WIDTH = ${dialogueModel.width.toFixed(5)}\nendglobals\nendlibrary\n`;}
